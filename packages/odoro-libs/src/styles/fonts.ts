/**
 * Loading Google Fonts families from the CDN.
 *
 * The font files are **never bundled**: this module builds the official
 * `css2` URL and injects the `<link>` tags into the document — preconnects
 * included. The browser then downloads the weights actually used, as WOFF2
 * sliced by Unicode range, from the Google CDN. This is the lightest path: a
 * few hundred bytes of CSS on the application side, the rest in a shared
 * cache.
 *
 * The {@link GOOGLE_FONTS} registry lists the most used families so as to
 * offer autocompletion and the right fallback stack; **any** family of the
 * Google Fonts catalog is still accepted as a free-form string.
 *
 * @example
 * import { loadGoogleFonts, applyFontFamily } from '@odoro-cli/libs/styles'
 *
 * loadGoogleFonts([
 *   { family: 'Inter', weights: [400, 500, 700] },
 *   { family: 'JetBrains Mono' },
 * ])
 * applyFontFamily('sans', 'Inter')
 *
 * @module
 */

