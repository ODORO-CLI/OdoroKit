/**
 * Collects the version of every published package of the workspace.
 *
 * ## Why the CLI cannot guess it
 *
 * The scaffolder writes the versions of the Odoro packages into the manifest of
 * the created project. It used to set the CLI one on all of them, which was
 * right as long as the configuration kept them in a `fixed` group: the six
 * moved together, so the version of one was good for all.
 *
 * That group was removed — a minor on the libraries dragged the engine into a
 * major. The packages now move each at their own pace, and `odoro` at 1.0.3
 * asked for `@odoro-cli/libs@^1.0.3`, still at 1.0.2: a version that does not
 * exist, hence an `npm install` that fails as soon as the project is created.
 *
 * ## Why a collection at build time, and not a read at runtime
 *
 * `@odoro-cli/libs` is not a dependency of `odoro`: on the machine of whoever
 * creates a project, it is nowhere. The only occasion to know these numbers is
 * the build, here, in the workspace where the six manifests sit side by side.
 *
 * And it is the right moment: the version bump precedes the build, which
 * precedes the publication. What is collected is therefore exactly what goes
 * out to the registry.
 *
 * Usage:
 *
 *   node scripts/family-versions.mjs
 *
 * @module
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packages = resolve(here, '..', '..')
const output = resolve(here, '..', 'src', 'scaffold', 'family-versions.generated.ts')

/** The versions collected, by package name. */
const versions = {}

for (const directory of readdirSync(packages)) {
  let manifest
  try {
    manifest = JSON.parse(readFileSync(join(packages, directory, 'package.json'), 'utf8'))
  } catch {
    continue
  }

  // Private packages are never installed anywhere: announcing them would write
  // a dependency that cannot be found.
  if (manifest.private === true) continue
  if (typeof manifest.name !== 'string' || typeof manifest.version !== 'string') continue

  versions[manifest.name] = manifest.version
}

const lines = Object.keys(versions)
  .sort()
  .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(versions[name])},`)

writeFileSync(
  output,
  [
    '/* Generated by scripts/family-versions.mjs. Do not edit by hand.',
    '',
    '   The versions of the published packages of the workspace, collected at',
    '   build time. See the script for the reason. */',
    '',
    '/** Published version of every package of the family. */',
    'export const FAMILY_VERSIONS: Readonly<Record<string, string>> = {',
    ...lines,
    '}',
    '',
  ].join('\n'),
  'utf8',
)

console.log(`[family-versions] ${String(lines.length)} packages collected`)
